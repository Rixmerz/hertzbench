// Regenerates cli/examples_bundle.ts from the scripted-board scenarios in scenarios/examples/, so
// the `examples` command works from a compiled binary that has no checkout beside it.
//   deno run --allow-read --allow-write scripts/bundle-examples.ts
// The output is deterministic: files are sorted by name and line endings are normalised.

import { basename, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "@std/yaml";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const EXAMPLES_DIR = join(ROOT, "scenarios", "examples");
const BUNDLE_PATH = join(ROOT, "cli", "examples_bundle.ts");

export type BundledExample = { name: string; description: string; yaml: string };

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

/** True when anything under `value` is an `apk` key: the scenario needs a built Android app. */
function mentionsApk(value: unknown): boolean {
  if (Array.isArray(value)) return value.some(mentionsApk);
  if (!isRecord(value)) return false;
  return "apk" in value || Object.values(value).some(mentionsApk);
}

/**
 * A scenario goes into the bundle only when every node is a scripted board whose firmware, if
 * any, is an inline script (an object), and nothing names an APK. A firmware path, a flash image
 * or an APK is a file the bundle cannot carry, so a copied-out example would fail to run.
 */
export function isSelfContained(scenario: unknown): boolean {
  if (!isRecord(scenario) || !Array.isArray(scenario.nodes) || scenario.nodes.length === 0) {
    return false;
  }
  if (mentionsApk(scenario)) return false;
  return scenario.nodes.every((node) =>
    isRecord(node) && node.board === "scripted" && typeof node.firmware !== "string"
  );
}

const MAX_DESCRIPTION = 100;

/** The first sentence of the leading comment block, on one line of at most 100 characters. */
export function describe(yaml: string): string {
  const lines: string[] = [];
  for (const line of yaml.split("\n")) {
    const comment = /^#\s?(.*)$/.exec(line);
    if (comment === null) break;
    const text = comment[1]!.trim();
    if (text === "") break; // a blank comment line ends the first paragraph
    lines.push(text);
  }
  const paragraph = lines.join(" ");
  const end = paragraph.search(/\.(\s|$)/);
  const sentence = end === -1 ? paragraph : paragraph.slice(0, end + 1);
  if (sentence.length <= MAX_DESCRIPTION) return sentence;
  const room = sentence.slice(0, MAX_DESCRIPTION - 3);
  return `${room.slice(0, room.lastIndexOf(" "))}...`;
}

/** Reads every self-contained scenario in `dir`, sorted by name. */
export async function collectExamples(dir: string = EXAMPLES_DIR): Promise<BundledExample[]> {
  const found: BundledExample[] = [];
  for await (const entry of Deno.readDir(dir)) {
    if (!entry.isFile || !entry.name.endsWith(".yaml")) continue;
    const yaml = (await Deno.readTextFile(join(dir, entry.name))).replaceAll("\r\n", "\n");
    if (!isSelfContained(parse(yaml))) continue;
    const description = describe(yaml);
    if (description === "") throw new Error(`${entry.name}: no leading comment to describe it`);
    found.push({ name: basename(entry.name, ".yaml"), description, yaml });
  }
  return found.sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
}

/** The text of cli/examples_bundle.ts. */
export function renderBundle(examples: BundledExample[]): string {
  const entries = examples.map((example) =>
    [
      `  ${JSON.stringify(example.name)}: {`,
      `    description: ${JSON.stringify(example.description)},`,
      `    yaml: ${JSON.stringify(example.yaml)},`,
      "  },",
    ].join("\n")
  );
  return [
    "// deno-fmt-ignore-file", // the generator owns the layout; fmt would rewrap and requote it
    "// GENERATED by scripts/bundle-examples.ts from scenarios/examples/. Do not edit by hand:",
    "// run `deno run --allow-read --allow-write scripts/bundle-examples.ts` instead.",
    "",
    "export type BundledExample = { description: string; yaml: string };",
    "",
    "export const BUNDLED_EXAMPLES: Readonly<Record<string, BundledExample>> = {",
    ...entries,
    "};",
    "",
  ].join("\n");
}

if (import.meta.main) {
  const examples = await collectExamples();
  await Deno.writeTextFile(BUNDLE_PATH, renderBundle(examples));
  console.log(`bundle-examples: ${examples.length} examples -> ${BUNDLE_PATH}`);
}
